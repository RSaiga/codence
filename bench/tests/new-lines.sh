#!/usr/bin/env bash
# lints/new-lines.sh reports a comment rule's findings only on added lines, and the comment rules keep
# doc comments, lint directives, license lines and Given/When/Then.
set -euo pipefail
kit="$(cd "$(dirname "$0")/../.." && pwd)"
export AST_GREP="${AST_GREP:-$(command -v ast-grep >/dev/null && echo ast-grep || echo "npx -y -p @ast-grep/cli@0.51.3 ast-grep")}"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }
cd "$tmp" && git init -q && git config user.email t@example.invalid && git config user.name t
mkdir -p rules src && cp "$kit"/lints/comments/*.yml rules/ && printf 'ruleDirs: [rules]\n' > sgconfig.yml
printf '// old comment stays\nexport const a = 1\n' > src/a.ts
printf 'fn main() {}\n' > src/b.rs
git add -A && git commit -qm base
cat > src/a.ts <<'TS'
// old comment stays
export const a = 1
const url = "http://example.com/not-a-comment"
/** doc comment */
export function f() {
  // eslint-disable-next-line no-console
  console.log(url) // new trailing
}
test('x', () => {
  // Given
  // new plain
})
TS
cat > src/b.rs <<'RS'
/// doc
fn main() {
    let s = "// not a comment";
    /* new block */
}
RS
printf '# new python comment\nx = 1  # noqa: E501\n' > src/new.py
cat > src/c.go <<'GO'
// Package c is new.
package c

//go:generate stringer -type=State

// Add is documented.
func Add() int {
	// new inside
	return 1 //nolint:gomnd
}
GO
out="$(bash "$kit/lints/new-lines.sh" 2>&1)" && fail "expected findings, exit 0: $out"
got="$(printf '%s\n' "$out" | cut -d: -f1,2 | sort | tr '\n' ' ')"
want="src/a.ts:11 src/a.ts:7 src/b.rs:4 src/c.go:8 src/new.py:1 "
[ "$got" = "$want" ] || fail "findings: got '$got' want '$want' ($out)"
git add -A
out="$(bash "$kit/lints/new-lines.sh" --staged 2>&1)" && fail "staged: expected findings"
[ "$(printf '%s\n' "$out" | wc -l | tr -d ' ')" = 5 ] || fail "staged: $out"
git commit -qm change
bash "$kit/lints/new-lines.sh" >/dev/null || fail "nothing added since HEAD, but findings reported"
# Tool directives and generated files are kept; a plain comment in a JavaScript file is still reported.
mkdir -p keep
cat > keep/d.ts <<'TS'
/// <reference types="vite/client" />
// @vitest-environment jsdom
/* istanbul ignore next */
// c8 ignore next
/* v8 ignore start */
// oxlint-disable-next-line no-console
// deno-lint-ignore no-explicit-any
const m = import(/* webpackChunkName: "m" */ './m')
const n = import(/* @vite-ignore */ './n')
TS
printf '// @jest-environment node\n/* global jest */\nexport {}\n' > keep/e.js
printf 'import os  # nosec B404\nimport sys  # isort: skip\nx = 1  # pyright: ignore\n' > keep/f.py
cat > keep/g.go <<'GO'
// +build linux

package g

//export Add
func add() int {
	//line g.go:1
	return 1 // #nosec G101
}
GO
printf '// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\n\nfunc f() {\n\t// generated inside\n}\n' > keep/gen.go
printf '// @generated by a tool\n// generated note\nexport const g = 1\n' > keep/gen.ts
cat > keep/i.php <<'PHP'
<?php
/** Doc for f */
function f(): int {
    // phpcs:ignore Generic.Files.LineLength
    $x = 1; // @phpstan-ignore-next-line
    // @psalm-suppress MixedAssignment
    $s = "// not a comment";
    return $x;
}
#[Attr]
class C {}
PHP
printf '<?php\n# a new plain comment\n$k = 1;\n' > keep/j.php
printf '// a new plain comment\nexport const j = 1\n' > keep/h.js
out="$(bash "$kit/lints/new-lines.sh" HEAD 2>&1)" && fail "keep: expected the plain JavaScript comment"
[ "$(printf '%s\n' "$out" | cut -d: -f1,2 | sort | tr '\n' ' ')" = "keep/h.js:1 keep/j.php:2 " ] || fail "keep: only keep/h.js:1 and keep/j.php:2 should be reported, got: $out"
/bin/rm -r keep

# Installed the way init does it: script, rules and sgconfig.yml under .codence/lints, nothing at the root.
mkdir -p .codence/lints/comments && cp "$kit/lints/new-lines.sh" .codence/lints/ && mv rules/*.yml .codence/lints/comments/
printf 'ruleDirs: [comments]\n' > .codence/lints/sgconfig.yml && rm sgconfig.yml && rmdir rules
printf '\n.codence/\n' >> .git/info/exclude && git add -A && git commit -qm moved
printf 'export const b = 2 // new\n' >> src/a.ts
out="$(bash .codence/lints/new-lines.sh 2>&1)" && fail "installed copy: expected a finding"
[ "$(printf '%s\n' "$out" | cut -d: -f1)" = src/a.ts ] || fail "installed copy: $out"
echo "new-lines: only added comments are reported"
